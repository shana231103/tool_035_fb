# File: backend/app/domain/ports/bulk_import_repository.py
from typing import Protocol
from uuid import UUID
from app.domain.entities.batch_job import BatchJob
from app.domain.value_objects.bulk_import import AcceptedBulkReview, ImportMatch
from app.domain.value_objects.enums import JobStatus


class IBulkImportRepository(Protocol):
    async def get_by_import_id(self, import_id: UUID) -> BatchJob | None: ...
    async def find_content_matches(self, content_sha256: str, limit: int = 20) -> tuple[ImportMatch, ...]: ...
    async def insert_draft(self, job: BatchJob) -> None: ...
    async def accept_start(self, job_id: UUID, expected_revision: int,
                           expected_status: JobStatus, review: AcceptedBulkReview) -> bool: ...
    async def save_pause(self, job_id: UUID, expected_revision: int, reason: str) -> bool: ...
